#!/usr/bin/env python3
"""The PUAE sources the Android app builds, from PUAE's own Makefile.common.

    python3 tools/puae_sources.py

Writes android/app/src/main/cpp/puae_sources.cmake: PUAE_SRC, PUAE_INC and
PUAE_DEFS, relative to third_party/libretro-uae, the variables its
jni/Android.mk takes from Makefile.common (7-Zip and CHD on, as there).
Run again after moving the submodule.
"""
import os
import subprocess
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUAE = os.path.join(ROOT, "third_party", "libretro-uae")
OUT = os.path.join(ROOT, "android", "app", "src", "main", "cpp", "puae_sources.cmake")

MK = """CORE_DIR := .
SOURCES_C :=
CFLAGS += -DHAVE_7ZIP -D_7ZIP_ST
HAVE_CHD = 1
platform = android
include Makefile.common
print:
\t@echo "SRC $(SOURCES_C)"
\t@echo "INC $(INCFLAGS)"
\t@echo "DEFS $(CFLAGS)"
"""

with tempfile.NamedTemporaryFile("w", suffix=".mk", delete=False) as f:
    f.write(MK)
out = subprocess.run(["make", "-s", "-f", f.name, "print"], cwd=PUAE, capture_output=True, text=True,
                     check=True).stdout
os.unlink(f.name)
vals = {line.split(" ", 1)[0]: line.split(" ", 1)[1].split() for line in out.splitlines() if " " in line}
src = [s[2:] if s.startswith("./") else s for s in vals["SRC"]]
inc = [i[2:].lstrip("./") if i.startswith("-I") else i for i in vals["INC"]]
defs = [d[2:] for d in vals["DEFS"] if d.startswith("-D") and not d.startswith("-DGIT_VERSION")]  # CMake sets that
with open(OUT, "w") as o:
    o.write("# GENERATED by tools/puae_sources.py from third_party/libretro-uae/Makefile.common\n")
    o.write("set(PUAE_SRC\n" + "".join(f"    ${{PUAE}}/{s}\n" for s in src) + ")\n")
    o.write("set(PUAE_INC\n" + "".join(f"    ${{PUAE}}/{i}\n" if i else "    ${PUAE}\n" for i in inc) + ")\n")
    o.write("set(PUAE_DEFS\n" + "".join(f"    {d}\n" for d in defs) + ")\n")
print(f"{len(src)} sources, {len(inc)} include dirs, {len(defs)} defines -> {os.path.relpath(OUT, ROOT)}")
