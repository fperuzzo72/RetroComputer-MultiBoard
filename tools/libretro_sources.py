#!/usr/bin/env python3
"""The sources the Android app builds for each libretro core, from the core's
own Makefile.common.

    python3 tools/libretro_sources.py

Writes android/app/src/main/cpp/<core>_sources.cmake for every core below:
<NAME>_SRC, <NAME>_INC and <NAME>_DEFS, relative to its submodule under
third_party/, the variables its jni/Android.mk takes from Makefile.common.
Run again after moving a submodule.
"""
import os
import subprocess
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CPP = os.path.join(ROOT, "android", "app", "src", "main", "cpp")

# core: (submodule, CMake prefix, what Android.mk sets before the include,
#        the source variables, the defines variable)
CORES = {
    "puae": ("libretro-uae", "PUAE",
             "CFLAGS += -DHAVE_7ZIP -D_7ZIP_ST\nHAVE_CHD = 1\nplatform = android\n",
             "$(SOURCES_C)", "$(CFLAGS)"),
    "bluemsx": ("blueMSX-libretro", "BLUEMSX",
                "HAVE_COMPAT := 1\n",
                "$(SOURCES_C) $(SOURCES_CXX)", "$(COREDEFINES)"),
}

for core, (sub, name, pre, srcvars, defvar) in CORES.items():
    top = os.path.join(ROOT, "third_party", sub)
    mk = f"CORE_DIR := .\nSOURCES_C :=\n{pre}include Makefile.common\nprint:\n" \
         f"\t@echo \"SRC {srcvars}\"\n\t@echo \"INC $(INCFLAGS)\"\n\t@echo \"DEFS {defvar}\"\n"
    with tempfile.NamedTemporaryFile("w", suffix=".mk", delete=False) as f:
        f.write(mk)
    out = subprocess.run(["make", "-s", "-f", f.name, "print"], cwd=top, capture_output=True, text=True,
                         check=True).stdout
    os.unlink(f.name)
    vals = {line.split(" ", 1)[0]: line.split(" ", 1)[1].split() for line in out.splitlines() if " " in line}
    src = [s[2:] if s.startswith("./") else s for s in vals["SRC"]]
    inc = [i[2:].lstrip("./") if i.startswith("-I") else i for i in vals["INC"]]
    # GIT_VERSION is set in CMake: the generated one has a space in it
    defs = [d[2:] for d in vals["DEFS"] if d.startswith("-D") and not d.startswith("-DGIT_VERSION")]
    path = os.path.join(CPP, f"{core}_sources.cmake")
    with open(path, "w") as o:
        o.write(f"# GENERATED by tools/libretro_sources.py from third_party/{sub}/Makefile.common\n")
        o.write(f"set({name}_SRC\n" + "".join(f"    ${{{name}}}/{s}\n" for s in src) + ")\n")
        o.write(f"set({name}_INC\n" + "".join(f"    ${{{name}}}/{i}\n" if i else f"    ${{{name}}}\n"
                                              for i in inc) + ")\n")
        o.write(f"set({name}_DEFS\n" + "".join(f"    {d}\n" for d in defs) + ")\n")
    print(f"{core}: {len(src)} sources, {len(inc)} include dirs, {len(defs)} defines -> "
          f"{os.path.relpath(path, ROOT)}")
